def _header(before: dict[str, Any], after: dict[str, Any], output_dir: Path) -> str:
    def run_card(label: str, snap: dict[str, Any]) -> str:
        manifest = snap["results"].get("manifest", {})
        git = manifest.get("git", {})
        tree = "<span class='pill pill-warning'>uncommitted changes</span>" if git.get("dirty") else "<span class='pill pill-good'>clean tree</span>"
        link = os.path.relpath(snap["path"] / "report-routing.html", output_dir)
        return f"""<div class="card"><h3>{label}</h3><dl class="glance-list">
  <div><dt>Run</dt><dd class="mono">{escape(snap['results']['run_id'])}</dd></div>
  <div><dt>Started</dt><dd>{escape(_fmt_time(manifest.get('started_at')))}</dd></div>
  <div><dt>Commit</dt><dd class="mono">{escape((git.get('commit') or 'unknown')[:12])} <span class="muted">on {escape(git.get('branch') or '?')}</span> {tree}</dd></div>
  <div><dt>Accuracy fingerprint</dt><dd class="mono">{escape(snap['results'].get('fingerprint', ''))}</dd></div>
  <div><dt>Full reports</dt><dd><a href="{escape(link)}">{escape(SUITE_TITLES['routing'])}</a> ·
    <a href="{escape(os.path.relpath(snap['path'] / 'index.html', output_dir))}">all reports for this run</a></dd></div>
</dl></div>"""

    return f"""
<header class="hero">
  <p class="eyebrow">Ops Signals · Benchmark evidence · Before and after</p>
  <h1>Router fix: before and after, on the same data</h1>
  <p class="lede">Two complete benchmark runs, one before and one after a change to how the router picks analyzers. Same datasets, same
  answer keys, same baselines; only the code changed. Every number here comes from the two snapshots below, each produced by one command
  against a known commit.</p>
</header>
<section><div class="two-col">{run_card("Before", before)}{run_card("After", after)}</div></section>"""


def _glance(before: dict[str, Any], after: dict[str, Any], rows: list[dict[str, Any]]) -> str:
    matched_before = sum(_router_matches(row, "before") for row in rows)
    matched_after = sum(_router_matches(row, "after") for row in rows)
    improved = [row for row in rows if (_router(row, "after") or {}).get("value", 0) > (_router(row, "before") or {}).get("value", 0)]
    worse = [row for row in rows if (_router(row, "after") or {}).get("value", 0) < (_router(row, "before") or {}).get("value", 0)]
    if worse:
        verdict = ("warning", f"Better on {len(improved)} of {len(rows)} datasets, worse on {len(worse)}.")
    elif matched_after > matched_before:
        verdict = ("good", f"Better or unchanged on every dataset; router picks now match or beat running everything on {matched_after} of {len(rows)}.")
    else:
        verdict = ("warning", "No dataset got worse, but routing still doesn't match running everything.")
    items = (
        ("What it tests", "Whether the router change made the product more accurate on the same data, and whether the router now keeps up with running every analyzer and with simple baselines."),
        ("Data source", "The datasets from both runs: " + ", ".join(escape(row["after"]["dataset"]) for row in rows) + "."),
        ("Ground truth", "Each dataset's own answer key. NAB, UCR and TCPD labels come from outside researchers; the behavior scenarios are this project's own."),
        ("Our result", f"<b>Router picks match or beat running everything on {matched_after} of {len(rows)} datasets, up from {matched_before}.</b> "
                       f"Router picks scored higher after the change on {len(improved)} of {len(rows)}, lower on {len(worse)}."),
        ("What good looks like", "Every dataset improves or holds, the other methods score the same in both runs (so the change is the only difference), "
                                 "and router picks end up at least as accurate as running everything, for fewer analyzer runs."),
    )
    rows_html = "".join(f"<div><dt>{label}</dt><dd>{value}</dd></div>" for label, value in items)
    return f"""
<section class="glance" aria-label="At a glance">
  <h2>At a glance</h2>
  <div class="card glance-card">
    <p class="glance-verdict">{_verdict_pill(verdict)} {escape(verdict[1])}</p>
    <dl class="glance-list">{rows_html}</dl>
  </div>
</section>"""


def _tiles(rows: list[dict[str, Any]], before: dict[str, Any], after: dict[str, Any]) -> str:
    tiles = []
    for row in rows:
        b, a = _router(row, "before"), _router(row, "after")
        if not b or not a:
            continue
        caption = f"router picks, before → after · {row['after']['measure']}"
        value = f"{_fmt_value(row['suite'], b['value'])} → {_fmt_value(row['suite'], a['value'])}"
        tiles.append(_tile(_short_dataset(row["suite"]), value, caption, "good" if a["value"] > b["value"] else ("critical" if a["value"] < b["value"] else None)))
    runs = [(row, _router(row, "before"), _router(row, "after"), row["after"]["cells"].get("all_analyzers")) for row in rows]
    everything = sum(e["analyzer_runs"] for _, _, _, e in runs if e)
    router_after = sum(a["analyzer_runs"] for _, _, a, e in runs if a and e)
    if everything:
        tiles.append(_tile("Analyzer runs", f"{_pct(1 - router_after / everything)}", "fewer than running every analyzer, after the change, across these datasets", None))
    return f'<section aria-label="Headline numbers"><div class="tiles">{"".join(tiles)}</div></section>'


def _main_table(rows: list[dict[str, Any]]) -> str:
    head = "".join(f"<th>{escape(ROUTING_LABELS[m])}<div class='small muted'>after</div></th>" for m in BASELINE_METHODS)
    body = []
    for row in rows:
        b, a = _router(row, "before"), _router(row, "after")
        cells = []
        for method in BASELINE_METHODS:
            cell = row["after"]["cells"].get(method)
            cells.append(f"<td>{cell['text']}</td>" if cell else "<td class='muted small'>doesn't apply</td>")
        body.append(
            f"<tr><td><b>{escape(_short_dataset(row['suite']))}</b><div class='small muted'>{escape(row['after']['measure'])}</div></td>"
            f"<td>{b['text'] if b else '-'}</td><td>{a['text'] if a else '-'}</td>"
            f"<td class='num'>{_delta(b and b['value'], a and a['value'], fmt=_delta_format(row['suite']))}</td>{''.join(cells)}"
            f"<td>{_verdict_pill(row['before']['verdict'])}<div class='small'>{escape(row['before']['verdict'][1])}</div></td>"
            f"<td>{_verdict_pill(row['after']['verdict'])}<div class='small'>{escape(row['after']['verdict'][1])}</div></td></tr>"
        )
    return f"""
<section id="comparison">
  <h2>Does routing help? Before and after</h2>
  <p class="section-lede">Each row is one dataset. The first two result columns are the product as users get it
  (<b>{escape(ROUTING_LABELS['router_picks'])}</b>) before and after the change. The other methods are shown from the after run; the next
  section checks they scored the same in both. Higher is better in every row. "Matches" means within 2% of running everything's score.</p>
  <div class="table-wrap"><table>
    <thead><tr><th>Dataset and measure</th><th>{escape(ROUTING_LABELS['router_picks'])}<div class='small muted'>before</div></th>
    <th>{escape(ROUTING_LABELS['router_picks'])}<div class='small muted'>after</div></th><th class="num">Change</th>{head}
    <th>Routing verdict, before</th><th>Routing verdict, after</th></tr></thead>
    <tbody>{''.join(body)}</tbody>
  </table></div>
</section>"""


def _baselines_check(rows: list[dict[str, Any]]) -> str:
    differences = []
    compared = 0
    for row in rows:
        for method in BASELINE_METHODS:
            b, a = row["before"]["cells"].get(method), row["after"]["cells"].get(method)
            if not b or not a:
                continue
            compared += 1
            if abs(b["value"] - a["value"]) > 1e-9:
                differences.append(f"<li>{escape(_short_dataset(row['suite']))}, {escape(ROUTING_LABELS[method])}: "
                                   f"{_fmt_value(row['suite'], b['value'])} before, {_fmt_value(row['suite'], a['value'])} after</li>")
    if not differences:
        return f"""<div class="callout callout-good"><b>Only the router changed.</b> All {compared} results of the other methods
(all analyzers, z-score only, static threshold) are identical in both runs, so the differences above come from the router change, not
from the data, the scoring or run-to-run noise.</div>"""
    return f"""<div class="callout callout-warning"><b>Some other methods scored differently between the runs</b>, so not every difference
above is the router change alone:<ul class="notes">{''.join(differences)}</ul></div>"""


def _cost_table(rows: list[dict[str, Any]]) -> str:
    body = []
    for row in rows:
        b, a, everything = _router(row, "before"), _router(row, "after"), row["after"]["cells"].get("all_analyzers")
        if not b or not a:
            continue

        def seconds(cell):
            if not cell or cell.get("seconds") is None:
                return "-"
            return f"{cell['seconds'] / 60:.1f} min" if cell["seconds"] >= 120 else f"{cell['seconds']:.1f} s"

        body.append(
            f"<tr><td>{escape(_short_dataset(row['suite']))}</td>"
            f"<td class='num'>{b['analyzer_runs']:,}</td><td class='num'>{a['analyzer_runs']:,}</td>"
            f"<td class='num'>{everything['analyzer_runs']:,}</td>"
            f"<td class='num'>{seconds(b)}</td><td class='num'>{seconds(a)}</td><td class='num'>{seconds(everything)}</td></tr>"
        )
    return f"""
<section id="cost">
  <h2>What it cost</h2>
  <p class="section-lede">Analyzer runs count one analyzer executed on one series (or one scheduled run, for NAB's replay). Time is
  wall-clock on the machine that ran each snapshot, so compare within a row.</p>
  <div class="table-wrap"><table>
    <thead><tr><th rowspan="2">Dataset</th><th colspan="3" class="num">Analyzer runs</th><th colspan="3" class="num">Time</th></tr>
    <tr><th class="num">Router picks, before</th><th class="num">Router picks, after</th><th class="num">All analyzers</th>
    <th class="num">Router picks, before</th><th class="num">Router picks, after</th><th class="num">All analyzers</th></tr></thead>
    <tbody>{''.join(body)}</tbody>
  </table></div>
</section>"""


def _nab_changes(before: dict[str, Any], after: dict[str, Any]) -> str:
    nb, na = before["results"]["suites"].get("nab"), after["results"]["suites"].get("nab")
    if not nb or not na:
        return ""
    headline = str(na["settings"]["headline_threshold"])
    ob, oa = nb["overall"]["replay"][headline], na["overall"]["replay"][headline]
    official = ""
    if before["official"] and after["official"]:
        name_b, name_a = nb["detector_names"]["replay"], na["detector_names"]["replay"]
        profiles = [("standard", "Standard"), ("reward_low_FP_rate", "Fewer false alarms"), ("reward_low_FN_rate", "Fewer misses")]
        official = "".join(
            f"<tr><td>Official NAB score, {label} profile</td><td class='num'>{float(before['official']['final'].get(name_b, {}).get(key, 0)):.1f}</td>"
            f"<td class='num'>{float(after['official']['final'].get(name_a, {}).get(key, 0)):.1f}</td>"
            f"<td class='num'>{_delta(float(before['official']['final'].get(name_b, {}).get(key, 0)), float(after['official']['final'].get(name_a, {}).get(key, 0)))}</td></tr>"
            for key, label in profiles
        )
    lines = [
        ("Incident windows caught", ob["detected_windows"], oa["detected_windows"], True),
        ("Alarms", ob["alarms"], oa["alarms"], None),
        ("False alarms", ob["false_alarms"], oa["false_alarms"], False),
    ]
    metric_rows = "".join(
        f"<tr><td>{label}</td><td class='num'>{b:,}</td><td class='num'>{a:,}</td><td class='num'>{_delta(b, a, fmt='{:+,.0f}', higher_is_better=higher_better)}</td></tr>"
        for label, b, a, higher_better in lines
    )
    metric_rows += (
        f"<tr><td>Alarm precision</td><td class='num'>{_pct(ob['alarm_precision'])}</td><td class='num'>{_pct(oa['alarm_precision'])}</td>"
        f"<td class='num'>{_delta(ob['alarm_precision'] * 100, oa['alarm_precision'] * 100, fmt='{:+.1f} pts')}</td></tr>"
    )

    series_b = {s["series"]: s for s in nb["series"]}
    gained, lost = [], []
    for item in na["series"]:
        earlier = series_b.get(item["series"])
        if not earlier:
            continue
        b = earlier["modes"]["replay"]["headline"]["detected_windows"]
        a = item["modes"]["replay"]["headline"]["detected_windows"]
        if a > b:
            gained.append((item["series"], b, a, item["modes"]["replay"]["headline"]["windows"]))
        elif a < b:
            lost.append((item["series"], b, a, item["modes"]["replay"]["headline"]["windows"]))
    flips = "".join(
        f"<tr><td class='mono small'>{escape(name)}</td><td class='num'>{b}/{total}</td><td class='num'>{a}/{total}</td></tr>"
        for name, b, a, total in sorted(gained + lost, key=lambda item: item[2] - item[1], reverse=True)
    ) or "<tr><td colspan='3' class='muted'>No series changed.</td></tr>"
    return f"""
<section id="nab">
  <h2>NAB: router picks, before and after</h2>
  <p class="section-lede">{len(na['series'])} series, replay (causal) mode, alarms at confidence ≥ {escape(headline)}. The official score is
  NAB's own scorer, 0 = never alarming, 100 = perfect.</p>
  <div class="table-wrap"><table><thead><tr><th>Measure</th><th class="num">Before</th><th class="num">After</th><th class="num">Change</th></tr></thead>
  <tbody>{official}{metric_rows}</tbody></table></div>
  <h3 class="sub">Series where the incidents caught changed ({len(gained)} gained, {len(lost)} lost)</h3>
  <div class="table-wrap scroll-y"><table><thead><tr><th>Series</th><th class="num">Windows caught, before</th><th class="num">After</th></tr></thead>
  <tbody>{flips}</tbody></table></div>
</section>"""


def _ucr_changes(before: dict[str, Any], after: dict[str, Any]) -> str:
    ub, ua = before["results"]["suites"].get("ucr"), after["results"]["suites"].get("ucr")
    if not ub or not ua:
        return ""
    earlier = {s["number"]: s for s in ub["series"]}
    gained, lost = [], []
    for s in ua["series"]:
        b = earlier.get(s["number"])
        if not b:
            continue
        was, now = b["methods"]["product"]["correct"], s["methods"]["product"]["correct"]
        if now and not was:
            gained.append(s)
        elif was and not now:
            lost.append(s)
    pb, pa = ub["summary"]["overall"]["product"], ua["summary"]["overall"]["product"]

    def series_list(items: list[dict[str, Any]]) -> str:
        if not items:
            return "<p class='muted small'>None.</p>"
        cells = "".join(
            f"<tr><td class='num'>{s['number']}</td><td class='mono small'>{escape(s['name'])}</td><td>{escape(s['domain'])}</td>"
            f"<td class='small mono'>{escape(', '.join(s['methods']['product'].get('executed_analyzers') or []))}</td></tr>"
            for s in items
        )
        return f"<div class='table-wrap scroll-y'><table><thead><tr><th class='num'>#</th><th>Series</th><th>Domain</th><th>Analyzers run, after</th></tr></thead><tbody>{cells}</tbody></table></div>"

    return f"""
<section id="ucr">
  <h2>UCR: router picks, before and after</h2>
  <div class="table-wrap"><table><thead><tr><th>Measure</th><th class="num">Before</th><th class="num">After</th><th class="num">Change</th></tr></thead><tbody>
  <tr><td>Anomalies located (of {ua['summary']['overall']['series']})</td><td class="num">{pb['correct']}</td><td class="num">{pa['correct']}</td><td class="num">{_delta(pb['correct'], pa['correct'], fmt='{:+.0f}')}</td></tr>
  <tr><td>Series given an answer at all</td><td class="num">{pb['answered']}</td><td class="num">{pa['answered']}</td><td class="num">{_delta(pb['answered'], pa['answered'], fmt='{:+.0f}')}</td></tr>
  <tr><td>Correct answer anywhere in the ranked findings</td><td class="num">{pb['found_anywhere']}</td><td class="num">{pa['found_anywhere']}</td><td class="num">{_delta(pb['found_anywhere'], pa['found_anywhere'], fmt='{:+.0f}')}</td></tr>
  </tbody></table></div>
  <h3 class="sub">Newly located after the change ({len(gained)})</h3>{series_list(gained)}
  <h3 class="sub">Located before, missed after ({len(lost)})</h3>{series_list(lost)}
</section>"""


def _tcpd_changes(before: dict[str, Any], after: dict[str, Any]) -> str:
    tb, ta = before["results"]["suites"].get("tcpd"), after["results"]["suites"].get("tcpd")
    if not tb or not ta:
        return ""
    earlier = {s["series"]: s for s in tb["series"]}
    changed = []
    for s in ta["series"]:
        b = earlier.get(s["series"])
        if b and abs(b["scores"]["product"]["f1"] - s["scores"]["product"]["f1"]) > 1e-9:
            changed.append((s["series"], b["scores"]["product"]["f1"], s["scores"]["product"]["f1"], b["executed_analyzers"], s["executed_analyzers"]))
    rows = "".join(
        f"<tr><td class='mono small'>{escape(name)}</td><td class='num'>{b:.3f}</td><td class='num'>{a:.3f}</td><td class='num'>{_delta(b, a, fmt='{:+.3f}')}</td>"
        f"<td class='small mono'>{escape(', '.join(ab))}</td><td class='small mono'>{escape(', '.join(aa))}</td></tr>"
        for name, b, a, ab, aa in changed
    ) or "<tr><td colspan='6' class='muted'>No series changed.</td></tr>"
    return f"""
<section id="tcpd">
  <h2>TCPD: series whose change-point F1 changed</h2>
  <div class="table-wrap scroll-y"><table><thead><tr><th>Series</th><th class="num">F1 before</th><th class="num">F1 after</th><th class="num">Change</th>
  <th>Analyzers run, before</th><th>Analyzers run, after</th></tr></thead><tbody>{rows}</tbody></table></div>
</section>"""


def _behavior_changes(before: dict[str, Any], after: dict[str, Any]) -> str:
    bb, ba = before["results"]["suites"].get("behavior"), after["results"]["suites"].get("behavior")
    if not bb or not ba or not ba["scenarios"] or "default_mode_evaluation" not in ba["scenarios"][0]:
        return ""
    earlier = {s["scenario"]["id"]: s for s in bb["scenarios"]}

    def analyzers(evaluation: dict[str, Any]) -> str:
        return "<br>".join(f"<span class='mono'>{escape(m)}</span>: {escape(', '.join(a) or 'none')}" for m, a in (evaluation.get("analyzers_by_metric") or {}).items())

    rows = []
    for s in ba["scenarios"]:
        b = earlier.get(s["scenario"]["id"])
        if not b or "default_mode_evaluation" not in b:
            continue
        eb, ea = b["default_mode_evaluation"], s["default_mode_evaluation"]
        rows.append(
            f"<tr><td>{escape(s['scenario']['name'])}</td><td>{escape(eb['status'])}<div class='small'>{analyzers(eb)}</div></td>"
            f"<td>{escape(ea['status'])}<div class='small'>{analyzers(ea)}</div></td></tr>"
        )
    return f"""
<section id="behavior">
  <h2>Cross-metric behaviors: router picks, before and after</h2>
  <div class="table-wrap"><table><thead><tr><th>Scenario</th><th>Before (analyzers run per metric)</th><th>After</th></tr></thead>
  <tbody>{''.join(rows)}</tbody></table></div>
</section>"""


def _still_weak(rows: list[dict[str, Any]]) -> str:
    items = []
    for row in rows:
        router = _router(row, "after")
        if not router:
            continue
        ahead = [
            (ROUTING_LABELS[m], row["after"]["cells"][m])
            for m in BASELINE_METHODS
            if row["after"]["cells"].get(m) and row["after"]["cells"][m]["value"] > router["value"]
        ]
        for label, cell in ahead:
            items.append(
                f"<li><b>{escape(_short_dataset(row['suite']))}:</b> {escape(label)} scores {_fmt_value(row['suite'], cell['value'])}, "
                f"router picks {_fmt_value(row['suite'], router['value'])}.</li>"
            )
    if not items:
        return ""
    return f"""
<section id="still-weak">
  <h2>Still behind after the change</h2>
  <div class="card"><p>Where another method still scores higher than router picks, on the after run:</p><ul class="notes">{''.join(items)}</ul></div>
</section>"""


def _code_changes(before: dict[str, Any], after: dict[str, Any]) -> str:
    commit_b = before["results"]["manifest"]["git"].get("commit")
    commit_a = after["results"]["manifest"]["git"].get("commit")
    if not commit_b or not commit_a:
        return ""
    try:
        log = subprocess.run(
            ["git", "log", "--format=%h%x09%s", f"{commit_b}..{commit_a}"], cwd=PROJECT_ROOT, capture_output=True, text=True, check=True
        ).stdout.strip().splitlines()
    except (OSError, subprocess.CalledProcessError):
        log = []
    items = "".join(
        f"<li><span class='mono'>{escape(line.split(chr(9))[0])}</span> {escape(line.split(chr(9), 1)[-1])}</li>" for line in log
    ) or "<li class='muted'>Commit history between the two runs isn't available in this checkout.</li>"
    return f"""
<section id="code">
  <h2>What changed in the code</h2>
  <p class="section-lede">Commits between <span class="mono">{escape(commit_b[:12])}</span> and <span class="mono">{escape(commit_a[:12])}</span>:</p>
  <ul class="notes">{items}</ul>
</section>"""


