BASELINE_METHODS = [m for m in ROUTING_METHODS if m != "router_picks"]


def load_snapshot(path: Path) -> dict[str, Any]:
    path = path.resolve()
    results = json.loads((path / "results.json").read_text(encoding="utf-8"))
    official = load_official_nab(path / "raw" / "nab_official")
    return {"path": path, "results": results, "official": official, "rows": routing_comparison(results.get("suites", {}), official)}


def render_compare(before: dict[str, Any], after: dict[str, Any], output_dir: Path) -> str:
    rows = _paired_rows(before, after)
    body = [
        _header(before, after, output_dir),
        _glance(before, after, rows),
        _tiles(rows, before, after),
        _main_table(rows),
        _baselines_check(rows),
        _cost_table(rows),
        _nab_changes(before, after),
        _ucr_changes(before, after),
        _tcpd_changes(before, after),
        _behavior_changes(before, after),
        _still_weak(rows),
        _code_changes(before, after),
    ]
    title = f"Ops Signals Benchmark · Before and after · {before['results']['run_id']} vs {after['results']['run_id']}"
    footer = (
        "Generated by <span class='mono'>benchmark/report_compare.py</span> from the two snapshots' "
        "<span class='mono'>results.json</span> files; nothing was rerun."
    )
    return _document(title, "\n".join(part for part in body if part), footer=footer)


def write_compare(before_path: Path, after_path: Path, output: Path | None = None) -> Path:
    before, after = load_snapshot(before_path), load_snapshot(after_path)
    output = output or (after["path"] / f"compare-{before['results']['run_id']}.html")
    output.write_text(render_compare(before, after, output.parent.resolve()), encoding="utf-8")
    return output


# --- data -----------------------------------------------------------------------------------


def _paired_rows(before: dict[str, Any], after: dict[str, Any]) -> list[dict[str, Any]]:
    """The routing rows present in both snapshots, keyed by suite, in the after snapshot's order."""
    earlier = {row["suite"]: row for row in before["rows"]}
    return [{"suite": row["suite"], "before": earlier[row["suite"]], "after": row} for row in after["rows"] if row["suite"] in earlier]


def _router(row: dict[str, Any], side: str) -> dict[str, Any] | None:
    return row[side]["cells"].get("router_picks")


def _delta(before: float | None, after: float | None, *, fmt: str = "{:+.1f}", higher_is_better: bool | None = True) -> str:
    """The change from before to after, colored good or bad by direction (neutral when neither)."""
    if before is None or after is None:
        return "<span class='muted'>-</span>"
    change = after - before
    if abs(change) < 1e-9:
        return "<span class='muted'>no change</span>"
    arrow = "▲" if change > 0 else "▼"
    if higher_is_better is None:
        return f"<span>{arrow} {fmt.format(change)}</span>"
    kind = "good" if (change > 0) == higher_is_better else "critical"
    return f"<span class='tile-{kind}'>{arrow} {fmt.format(change)}</span>"


def _router_matches(row: dict[str, Any], side: str) -> bool:
    return row[side]["verdict"][1].startswith(("Matches", "Better"))


