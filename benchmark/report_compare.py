"""One HTML page comparing two benchmark snapshots - typically before and after a change - on the
"does routing help?" question: router picks against running every analyzer and simple baselines,
per dataset, with what changed series by series.

    .venv/bin/python -m benchmark.report_compare BEFORE_SNAPSHOT AFTER_SNAPSHOT

Writes compare-<before run>.html into the AFTER snapshot (override with --output), linked to both
snapshots' full reports. Nothing is rerun; both snapshots must already exist, with NAB's official
score computed if the NAB row should show it.
"""

